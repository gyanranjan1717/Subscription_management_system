import bcrypt from 'bcryptjs';
import { getDb, execute, queryOne, resetDatabaseFile, runTransaction } from './database.js';
import { addDays, addMonthsClamped, todayIso } from '../lib/dates.js';
import { runBillingCycle } from '../services/billingEngine.js';
import { recordPayment } from '../services/paymentService.js';

/**
 * Rebuilds the database with a small, deterministic demo data set (all dates relative to today).
 * Demo accounts: admin@brightloop.com / staff@brightloop.com (Brightloop#2026),
 *                acme@corp.com / globex@biz.com (Customer#2026).
 * Large-scale data for performance checks is generated by scripts/benchmark.ts, not here.
 */
async function seed() {
  console.log('--- Rebuilding Brightloop database ---');
  resetDatabaseFile();
  const db = getDb();
  const today = todayIso();

  const staffHash = await bcrypt.hash('Brightloop#2026', 10);
  const custHash = await bcrypt.hash('Customer#2026', 10);

  const user = (email: string, hash: string, name: string, role: string, phone: string, company: string) =>
    Number(execute(
      'INSERT INTO users (email, password_hash, full_name, role, phone, company_name) VALUES (?, ?, ?, ?, ?, ?)',
      [email, hash, name, role, phone, company]
    ).lastInsertRowid);

  runTransaction(() => {
    const adminId = user('admin@brightloop.com', staffHash, 'Alex Mercer (Admin)', 'admin', '+1-555-0100', 'Brightloop HQ');
    user('staff@brightloop.com', staffHash, 'Sarah Jenkins (Billing Ops)', 'staff', '+1-555-0101', 'Brightloop Operations');
    const acme = user('acme@corp.com', custHash, 'David Miller', 'customer', '+1-555-0201', 'Acme Corporation');
    const globex = user('globex@biz.com', custHash, 'Elena Rostova', 'customer', '+1-555-0202', 'Globex International');

    const gst = Number(execute("INSERT INTO tax_rules (name, rate_percentage, is_default) VALUES ('Standard VAT / GST (18%)', 18, 1)").lastInsertRowid);
    execute("INSERT INTO tax_rules (name, rate_percentage) VALUES ('Reduced Software Rate (5%)', 5), ('Zero-Rated Export (0%)', 0)");

    const product = (name: string, type: string, price: number, cost: number, notes: string) =>
      Number(execute('INSERT INTO products (name, type, sales_price, cost_price, notes) VALUES (?, ?, ?, ?, ?)', [name, type, price, cost, notes]).lastInsertRowid);
    const core = product('Brightloop Core ERP Platform', 'software', 1200, 300, 'Flagship enterprise subscription software');
    const stdVariant = Number(execute("INSERT INTO product_variants (product_id, attribute_name, option_name, price_extra) VALUES (?, 'Brand', 'Standard Community', 0)", [core]).lastInsertRowid);
    const odooVariant = Number(execute("INSERT INTO product_variants (product_id, attribute_name, option_name, price_extra) VALUES (?, 'Brand', 'Odoo Certified Edition', 560)", [core]).lastInsertRowid);
    const bi = product('Advanced BI Analytics Add-On', 'addon', 350, 50, 'Real-time telemetry and reporting module');
    const sla = product('24/7 Priority SLA & Dedicated TAM', 'service', 500, 120, 'Direct line to technical account manager');
    const seat = product('Additional User Seat License', 'software', 45, 5, 'Per-seat user expansion pack');

    const plan = (name: string, interval: string, price: number, minQty: number, autoClose: number, canPause: number, canRenew: number) =>
      Number(execute(
        'INSERT INTO plans (name, billing_interval, price, min_quantity, auto_close, can_pause, can_renew) VALUES (?, ?, ?, ?, ?, ?, ?)',
        [name, interval, price, minQty, autoClose, canPause, canRenew]
      ).lastInsertRowid);
    const yearly = plan('Enterprise Yearly Contract', 'yearly', 12000, 1, 0, 1, 1);
    const monthly = plan('Standard Business Monthly', 'monthly', 1200, 1, 0, 1, 1);
    const weekly = plan('Pilot Sprint Weekly', 'weekly', 350, 1, 1, 0, 1);
    plan('High-Compute Daily Pass', 'daily', 50, 5, 1, 0, 0);

    const tpl1 = Number(execute("INSERT INTO quotation_templates (name, plan_id, validity_days, notes) VALUES ('SMB Growth Starter Template', ?, 30, 'Standard package for emerging companies')", [monthly]).lastInsertRowid);
    execute('INSERT INTO quotation_template_lines (template_id, product_id, variant_id, default_quantity) VALUES (?, ?, ?, 1), (?, ?, NULL, 5)', [tpl1, core, stdVariant, tpl1, seat]);
    const tpl2 = Number(execute("INSERT INTO quotation_templates (name, plan_id, validity_days, notes) VALUES ('Odoo Enterprise Strategic Stack', ?, 60, 'Premium configuration with Odoo brand variant and 24/7 SLA')", [yearly]).lastInsertRowid);
    execute('INSERT INTO quotation_template_lines (template_id, product_id, variant_id, default_quantity) VALUES (?, ?, ?, 1), (?, ?, NULL, 1), (?, ?, NULL, 10)', [tpl2, core, odooVariant, tpl2, sla, tpl2, seat]);

    const discount = (code: string, desc: string, type: string, value: number, minAmount: number, minQty: number, start: string, end: string, maxUses: number, uses: number, scope: string, target: number | null) =>
      Number(execute(
        `INSERT INTO discount_rules (code, description, discount_type, value, min_amount, min_quantity, start_date, end_date,
                                     max_uses, current_uses, applies_to, target_product_id, created_by)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        [code, desc, type, value, minAmount, minQty, start, end, maxUses, uses, scope, target, adminId]
      ).lastInsertRowid);
    const seats20 = discount('SEATS20', '20% off for 5 or more seats', 'percentage', 20, 0, 5, addDays(today, -365), addDays(today, 365), 100, 0, 'all', null);
    const ent500 = discount('ENTERPRISE500', '500 flat off orders above 2000', 'fixed', 500, 2000, 0, addDays(today, -365), addDays(today, 365), 50, 0, 'all', null);
    discount('ODOOPROMO15', '15% special discount on Core ERP', 'percentage', 15, 0, 0, addDays(today, -365), addDays(today, 365), 30, 0, 'product', core);
    discount('EXPIRED10', 'Expired summer discount', 'percentage', 10, 0, 0, addDays(today, -700), addDays(today, -400), 10, 10, 'all', null);

    const sub = (n: string, customer: number, planId: number, status: string, start: string, expiry: string | null, terms: string, disc: number | null, notes: string) =>
      Number(execute(
        `INSERT INTO subscriptions (subscription_number, customer_id, plan_id, status, start_date, expiry_date,
                                    next_period_index, next_billing_date, payment_terms, discount_rule_id, notes)
         VALUES (?, ?, ?, ?, ?, ?, 0, ?, ?, ?, ?)`,
        [n, customer, planId, status, start, expiry, start, terms, disc, notes]
      ).lastInsertRowid);
    const line = (subId: number, productId: number, variantId: number | null, qty: number, unit: number) =>
      execute(
        'INSERT INTO subscription_lines (subscription_id, product_id, variant_id, quantity, unit_price, tax_id, line_amount) VALUES (?, ?, ?, ?, ?, ?, ?)',
        [subId, productId, variantId, qty, unit, gst, unit * qty]
      );

    // Two months behind: a billing run must catch up every missed period, not just the latest.
    const s1 = sub('SUB-2026-000001', acme, monthly, 'Active', addMonthsClamped(today, -2), addMonthsClamped(today, 10), '30 Days Net', seats20, 'Key account contract');
    line(s1, core, odooVariant, 1, 1760); line(s1, bi, null, 1, 350); line(s1, seat, null, 6, 45);

    const s2 = sub('SUB-2026-000002', globex, monthly, 'Active', addMonthsClamped(today, -1), addMonthsClamped(today, 11), 'Immediate Payment', ent500, 'Globex business tier');
    line(s2, core, stdVariant, 1, 1200); line(s2, seat, null, 10, 45);

    const s3 = sub('SUB-2026-000003', acme, weekly, 'Active', addDays(today, -14), addDays(today, 90), '15 Days Net', null, 'Weekly pilot sprint');
    line(s3, bi, null, 2, 350);

    const s4 = sub('SUB-2026-000004', acme, yearly, 'Quotation', today, null, '15 Days Net', null, 'Pending customer executive sign-off');
    line(s4, core, odooVariant, 1, 1760); line(s4, sla, null, 1, 500);
    execute('UPDATE subscriptions SET quotation_sent_on = ?, quotation_valid_until = ? WHERE id = ?', [today, addDays(today, 60), s4]);

    const s5 = sub('SUB-2026-000005', globex, monthly, 'Draft', today, null, 'Immediate Payment', null, 'Sales draft being configured');
    line(s5, core, stdVariant, 1, 1200);

    const s6 = sub('SUB-2026-000006', acme, monthly, 'Paused', addMonthsClamped(today, -3), null, 'Immediate Payment', null, 'Paused per client request');
    line(s6, core, stdVariant, 1, 1200);
    execute('INSERT INTO subscription_pauses (subscription_id, paused_on) VALUES (?, ?)', [s6, addDays(today, -5)]);

    const s7 = sub('SUB-2025-000007', globex, yearly, 'Closed', '2025-01-01', '2025-12-31', 'Immediate Payment', null, 'Expired yearly contract');
    line(s7, core, stdVariant, 1, 1200);
    execute("UPDATE subscriptions SET closed_on = '2025-12-31', close_reason = 'EXPIRED' WHERE id = ?", [s7]);

    execute("INSERT INTO sequences (name, value) VALUES ('subscription', 7) ON CONFLICT(name) DO UPDATE SET value = 7");
  });

  // History for the demo: one run 45 days ago (confirmed, partly paid => overdue), the live run is left to the user.
  const past = addDays(today, -45);
  const first = runBillingCycle(past, { autoConfirm: true });
  const firstInvoice = queryOne<{ id: number; total_amount: number }>('SELECT id, total_amount FROM invoices ORDER BY id LIMIT 1');
  if (firstInvoice) {
    recordPayment({
      invoiceId: firstInvoice.id,
      amountCents: Math.round(firstInvoice.total_amount * 100 * 0.25),
      method: 'Credit Card',
      paymentDate: addDays(past, 10),
      reference: 'AUTH-VISA-4421',
      note: 'Partial deposit received'
    });
  }

  const dueNow = queryOne<{ n: number }>("SELECT COUNT(*) AS n FROM subscriptions WHERE status = 'Active' AND next_billing_date <= ?", [today])!.n;
  console.log(`Seeded. Historic run (${past}) created ${first.invoicesCreated} invoice(s).`);
  console.log(`${dueNow} active subscription(s) are due today: run billing to see catch-up, then run it again to see 0 new invoices.`);
  db.exec('PRAGMA wal_checkpoint(TRUNCATE);');
}

seed().catch(err => {
  console.error('Seed failed:', err);
  process.exit(1);
});
